// Диорит в жёрнове: шанс выбить адский кварц.
//
// У Create уже есть дробление диорита в КОЛЁСАХ (кварц с шансом 25%), но
// колёса — механизм не для начала игры. Здесь то же самое для жёрнова: дешевле
// поставить, зато шанс всего 5%.
//
// Диорит тратится всегда, кварц выпадает не каждый раз — так и просили.
// ═══════════════════════════════════════════════════════════════════════════

ServerEvents.recipes(event => {

    event.custom({
        type: 'create:milling',
        ingredients: [
            { item: 'minecraft:diorite' }
        ],
        results: [
            { id: 'minecraft:quartz', count: 1, chance: 0.05 }
        ],
        processing_time: 150
    }).id('mwxkhmycore:milling/diorite_to_quartz');

    console.info('[ZSMP] Жёрнов: диорит даёт кварц с шансом 5%');
});
